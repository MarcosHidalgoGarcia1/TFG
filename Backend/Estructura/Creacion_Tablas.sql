-- ==========================================
-- BASE DE DATOS GEOBUS
-- ESQUEMA DE TABLAS ACTUALIZADO
-- ==========================================

-- 1. LINEA
CREATE TABLE linea (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL
);


-- 2. PARADA
-- Una parada puede pertenecer a varias lineas.
CREATE TABLE parada (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    codigo_ctmas INTEGER UNIQUE,
    latitud DECIMAL(10, 7),
    longitud DECIMAL(10, 7)
);


-- 3. PARADA_LINEA
-- Relacion muchos a muchos entre paradas y lineas.
CREATE TABLE parada_linea (
    parada_id INTEGER NOT NULL,
    linea_id INTEGER NOT NULL,
    PRIMARY KEY (parada_id, linea_id),
    FOREIGN KEY (parada_id) REFERENCES parada(id),
    FOREIGN KEY (linea_id) REFERENCES linea(id)
);


-- 4. AUTOBUS
CREATE TABLE autobus (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);


-- 5. LINEA_AUTOBUS
CREATE TABLE linea_autobus (
    linea_id INTEGER NOT NULL,
    autobus_id INTEGER NOT NULL,
    PRIMARY KEY (linea_id, autobus_id),
    FOREIGN KEY (linea_id) REFERENCES linea(id),
    FOREIGN KEY (autobus_id) REFERENCES autobus(id)
);


-- 6. USUARIO
CREATE TABLE usuario (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(150) UNIQUE NOT NULL,
    contrasena VARCHAR(255) NOT NULL
);


-- 7. USUARIO_PARADA
CREATE TABLE usuario_parada (
    usuario_id INTEGER NOT NULL,
    parada_id INTEGER NOT NULL,
    favorito BOOLEAN DEFAULT FALSE,
    PRIMARY KEY (usuario_id, parada_id),
    FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    FOREIGN KEY (parada_id) REFERENCES parada(id)
);


-- 8. MONEDERO
CREATE TABLE monedero (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    tipo_tarjeta VARCHAR(50),
    saldo DECIMAL(10, 2),
    usuario_id INTEGER NOT NULL,
    FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);


-- 9. AVISO
CREATE TABLE aviso (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150),
    tiempo INTEGER,
    usuario_id INTEGER NOT NULL,
    parada_id INTEGER NOT NULL,
    FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    FOREIGN KEY (parada_id) REFERENCES parada(id)
);
